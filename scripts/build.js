#!/usr/bin/env node
"use strict";

/**
 * build.js — syncs data.json into data.js
 *
 * index.html works directly from a file:// path offline, where fetch() of
 * local JSON is blocked by browsers. So we mirror data.json into data.js
 * (a plain global assignment) and load that. data.json stays the single
 * source of truth; test.js checks that the two files agree.
 */

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const dataPath = path.join(root, "data.json");
const jsPath = path.join(root, "data.js");

const json = fs.readFileSync(dataPath, "utf8");
// Validate before writing the mirror.
JSON.parse(json);

const banner =
  "// Generated from data.json by scripts/build.js — edit data.json, then run " +
  "`node scripts/build.js`. Do not edit this file by hand.\n";
const output = banner + "window.FREE_LEARN_DATA = " + json.trim() + ";\n";

fs.writeFileSync(jsPath, output, "utf8");
console.log("Wrote data.js (" + output.length + " bytes) from data.json.");
